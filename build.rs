use std::path::PathBuf;

fn main() {
    // Embed a manifest that requests elevation: ETW real-time sessions require admin.
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        println!("cargo:rustc-link-arg-bins=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg-bins=/IGNORE:4099");
        // Resolve imported DLLs (pdh, wlanapi, ...) from System32 only, never from the exe's
        // folder: the exe runs elevated, often from Downloads.
        println!("cargo:rustc-link-arg-bins=/DEPENDENTLOADFLAG:0x800");
        println!("cargo:rustc-link-arg-bins=/MANIFESTUAC:level='requireAdministrator' uiAccess='false'");
    }
    tokens();
}

/// Generates the look (src/theme.rs) from lagscope-core's design/tokens.json (the version
/// pinned in Cargo.toml): `tokens.rs` (colours and sizes for the window) and `theme.css` (CSS
/// variables and the fonts, inlined, for the report).
fn tokens() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let t: serde_json::Value = serde_json::from_str(lagscope_core::design::TOKENS_JSON).expect("design/tokens.json is not valid JSON");

    let colors = t["color"].as_object().expect("tokens: color");
    let rgb = |name: &str| -> [u8; 3] {
        let hex = colors.get(name).and_then(|v| v.as_str()).unwrap_or_else(|| panic!("tokens: no colour {name}"));
        let h = hex.trim_start_matches('#');
        assert!(h.len() == 6, "tokens: colour {name} is not #RRGGBB");
        let b = |i: usize| u8::from_str_radix(&h[i..i + 2], 16).unwrap();
        [b(0), b(2), b(4)]
    };
    let num = |v: &serde_json::Value, what: &str| v.as_f64().unwrap_or_else(|| panic!("tokens: {what}"));

    let mut rs = String::from("// Generated by build.rs from lagscope-core's design/tokens.json. Do not edit.\n\n");
    let mut css = String::from(":root {\n");
    for name in colors.keys() {
        let ident = name.to_uppercase().replace('-', "_");
        rs += &format!("pub const {ident}: Color = Color({:?});\n", rgb(name));
        css += &format!("  --{name}: {};\n", colors[name].as_str().unwrap());
    }
    for (k, v) in t["radius"].as_object().expect("tokens: radius") {
        rs += &format!("pub const RADIUS_{}: f32 = {:.1};\n", k.to_uppercase().replace('-', "_"), num(v, "radius"));
        css += &format!("  --radius-{k}: {}px;\n", num(v, "radius"));
    }
    let touch = num(&t["size"]["touch-target"], "size.touch-target");
    rs += &format!("pub const TOUCH_TARGET: f32 = {touch:.1};\n");
    css += &format!("  --touch-target: {touch}px;\n");
    for (k, v) in t["font"].as_object().expect("tokens: font").iter().filter(|(k, _)| !k.starts_with('$')) {
        let family = v.as_str().expect("tokens: font");
        rs += &format!("pub const FONT_{}: &str = {family:?};\n", k.to_uppercase());
        css += &format!("  --font-{k}: \"{family}\";\n");
    }
    // Status: colour and shape per status key ("ok", "warn", "na").
    rs += "\n/// (status, colour, round, word) per status: a round dot or a square, and its word.\npub const STATUS: &[(&str, Color, bool, &str)] = &[\n";
    for (k, v) in t["status"].as_object().expect("tokens: status") {
        let color = v["color"].as_str().expect("tokens: status colour");
        let shape = v["shape"].as_str().expect("tokens: status shape");
        assert!(shape == "circle" || shape == "square", "tokens: unknown status shape {shape}");
        let word = v["word"].as_str().expect("tokens: status word");
        rs += &format!("    ({k:?}, Color({:?}), {}, {word:?}),\n", rgb(color), shape == "circle");
        css += &format!("  --status-{k}: var(--{color});\n  --status-{k}-radius: {};\n", if shape == "circle" { "50%" } else { "2px" });
    }
    rs += "];\n";
    let chart = &t["chart"];
    for k in ["line", "freeze", "device-pause"] {
        let c = chart[k].as_str().unwrap_or_else(|| panic!("tokens: chart.{k}"));
        rs += &format!("pub const CHART_{}: Color = Color({:?});\n", k.to_uppercase().replace('-', "_"), rgb(c));
        css += &format!("  --chart-{k}: var(--{c});\n");
    }
    css += "}\n";

    // The report's fonts, inlined (it is a single offline file): the latin subsets only, to keep
    // each report small; other characters fall back to the system font.
    let fonts = manifest.join("src/fonts");
    for (family, file) in [("display", "space-grotesk"), ("text", "inter"), ("mono", "jetbrains-mono")] {
        let p = fonts.join(format!("{file}-latin.woff2"));
        println!("cargo:rerun-if-changed={}", p.display());
        let data = std::fs::read(&p).unwrap_or_else(|e| panic!("reading {}: {e}", p.display()));
        let family = t["font"][family].as_str().unwrap();
        css += &format!(
            "@font-face {{ font-family: \"{family}\"; font-style: normal; font-display: swap; font-weight: 100 900; src: url(data:font/woff2;base64,{}) format(\"woff2\"); unicode-range: {LATIN}; }}\n",
            base64(&data)
        );
    }

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("tokens.rs"), rs).unwrap();
    std::fs::write(out.join("theme.css"), css).unwrap();
}

// Unicode range of fontsource's latin subset (the *-latin files in src/fonts).
const LATIN: &str = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";

fn base64(data: &[u8]) -> String {
    const A: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut s = String::with_capacity(data.len().div_ceil(3) * 4);
    for c in data.chunks(3) {
        let n = (c[0] as u32) << 16 | (*c.get(1).unwrap_or(&0) as u32) << 8 | *c.get(2).unwrap_or(&0) as u32;
        for i in 0..4 {
            s.push(if i <= c.len() { A[(n >> (18 - 6 * i) & 63) as usize] as char } else { '=' });
        }
    }
    s
}
